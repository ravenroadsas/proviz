#' The telemetry config a real recorder needs: every declared click,
#' grouped by app
#'
#' The click map (`registry$clicks`, see [pv_load_registry()]) is never
#' consulted when reading a *real* event log -- that log already
#' arrives with its weight totals pre-summed by the recorder (see
#' [pv_pull_subprocess_log()]). Its only consumer is the recorder
#' itself: for each app, which selector/kind/feature/event to listen
#' for, which step it counts toward, and how much weight to add. A step
#' declared in the registry with no click mapped onto it yet has
#' nothing a recorder could act on, so it's simply absent here -- this
#' is a telemetry config, not a copy of the ideal diagram.
#'
#' @param registry a [pv_load_registry()] result.
#' @return an unnamed list (a JSON array once exported), one entry per
#'   subprocess with at least one declared click: `process_id`,
#'   `subprocess`, `app`, `app_link` (`NA` if undeclared), `clicks` (a
#'   `data.frame`: `step_id`, `label`, `selector`, `kind`, `feature`,
#'   `event`, `weight` -- the click's own `id` is registry bookkeeping,
#'   not something the recorder replays, so it's dropped here). Length
#'   0 if no subprocess has a declared click yet.
#' @export
pv_telemetry_config <- function(registry) {
  stopifnot(inherits(registry, "pv_registry"))
  keys <- names(registry$clicks)
  if (length(keys) == 0) {
    return(list())
  }

  apps <- lapply(keys, function(key) {
    clicks <- registry$clicks[[key]]
    parts <- strsplit(key, "::", fixed = TRUE)[[1]]
    pid <- parts[1]
    sp <- parts[2]
    sub_row <- registry$subprocesses[
      registry$subprocesses$process_id == pid & registry$subprocesses$subprocess == sp,
    ]
    list(
      process_id = pid, subprocess = sp,
      app = sub_row$app[1], app_link = sub_row$app_link[1],
      clicks = clicks[, c("step_id", "label", "selector", "kind", "feature", "event", "weight")]
    )
  })
  names(apps) <- NULL
  apps
}

#' Export the telemetry config as a pinned JSON resource
#'
#' A thin write step around [pv_telemetry_config()] -- the board is
#' whatever the caller constructs (e.g. `pins::board_folder(path)` for
#' a local export, or a shared board -- `pins::board_connect()`,
#' `pins::board_s3()`, etc. -- so a recorder elsewhere can fetch the
#' latest version), so this package stays agnostic about where a real
#' organization actually wants its telemetry config to live.
#'
#' @param registry a [pv_load_registry()] result.
#' @param board a `pins` board (see `pins::board_folder()` and friends)
#'   to pin to.
#' @param name the pin's name. Defaults to `"telemetry_config"`.
#' @param title,description optional pin metadata, passed through to
#'   `pins::pin_write()`; a reasonable default is filled in for each if
#'   omitted.
#' @return `pins::pin_write()`'s own return value (the pin name),
#'   invisibly.
#' @export
pv_export_telemetry_config <- function(registry, board, name = "telemetry_config", title = NULL, description = NULL) {
  if (!requireNamespace("pins", quietly = TRUE)) {
    stop("proviz: pv_export_telemetry_config() needs the 'pins' package (Suggests) to write a pin.", call. = FALSE)
  }
  config <- pv_telemetry_config(registry)
  pins::pin_write(
    board, config, name = name, type = "json",
    title = title %||% sprintf("proviz telemetry config (%d app(s))", length(config)),
    description = description %||% paste(
      "Click -> step bindings for instrumenting each app's event log,",
      "generated by proviz::pv_export_telemetry_config()."
    )
  )
}
